#!/usr/bin/env python3
"""Writes the pass-through hooks of the PM4 writer trace (runtime/src/hle_gfx/pm4_trace.h).

Lists every recompiled guest function whose address falls in [first, last) in the generated code
(runtime/generated/), and writes runtime/src/hle_gfx/pm4_trace_hooks.gen.cpp with, for each, a
replacement that calls pm4_trace::Enter, the original function (__imp__sub_XXXXXXXX) and
pm4_trace::Exit. The file lists addresses from the player's own game, so git ignores it.

Then build with the trace on:
  cmake --preset <preset> -DAZURA_PM4_TRACE=ON && cmake --build --preset <preset>-relwithdebinfo

Usage: scripts/hle/gen_pm4_trace_hooks.py FIRST LAST [generated_dir]
  (FIRST and LAST in hex, for example 82AE0000 82B10000)
"""

import glob
import os
import re
import sys

FUNC_RE = re.compile(r"^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)", re.MULTILINE)
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "runtime", "src", "hle_gfx", "pm4_trace_hooks.gen.cpp")


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    first, last = int(sys.argv[1], 16), int(sys.argv[2], 16)
    generated = sys.argv[3] if len(sys.argv) > 3 else os.path.join(REPO, "runtime", "generated", "default")
    addresses = set()
    for path in glob.glob(os.path.join(generated, "azura_recomp.*.cpp")):
        with open(path, encoding="utf-8", errors="replace") as f:
            for m in FUNC_RE.finditer(f.read()):
                address = int(m.group(1), 16)
                if first <= address < last:
                    addresses.add(address)
    if not addresses:
        sys.exit(f"No generated functions in {first:08X}-{last:08X} under {generated}")

    # Functions our own code already replaces (a second definition would not link); the trace
    # leaves them out and says so.
    hooked_re = re.compile(r'extern "C" void sub_([0-9A-F]{8})\(|REX_HOOK(?:_RAW)?\(sub_([0-9A-F]{8})')
    src = os.path.join(REPO, "runtime", "src")
    for root, _, files in os.walk(src):
        for name in files:
            if name.endswith((".cpp", ".mm")) and not name.endswith(".gen.cpp"):
                with open(os.path.join(root, name), encoding="utf-8", errors="replace") as f:
                    for m in hooked_re.finditer(f.read()):
                        hooked = int(m.group(1) or m.group(2), 16)
                        if hooked in addresses:
                            addresses.discard(hooked)
                            print(f"Skipping sub_{hooked:08X}: already replaced in {name}")
    addresses = sorted(addresses)

    lines = [
        "// Generated by scripts/hle/gen_pm4_trace_hooks.py: pass-through hooks of the PM4 writer",
        "// trace. Lists addresses from the player's own game; never committed.",
        "",
        '#include "hle_gfx/pm4_trace.h"',
        "",
        "#include <rex/hook.h>",
        "",
        "namespace azura::pm4_trace {",
        "const uint32_t kTracedFunctions[] = {",
    ]
    lines += [f"    0x{a:08X}," for a in addresses]
    lines += [
        "};",
        f"const size_t kTracedFunctionCount = {len(addresses)};",
        "}  // namespace azura::pm4_trace",
        "",
    ]
    for i, a in enumerate(addresses):
        name = f"sub_{a:08X}"
        lines += [
            f'extern "C" void __imp__{name}(PPCContext& __restrict ctx, uint8_t* base);',
            f"REX_HOOK_RAW({name}) {{",
            f"  azura::pm4_trace::Enter({i}, ctx, base);",
            f"  __imp__{name}(ctx, base);",
            f"  azura::pm4_trace::Exit({i}, base);",
            "}",
        ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(addresses)} hooks to {OUT}")


if __name__ == "__main__":
    main()
