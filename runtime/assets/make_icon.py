# ---------- Cog: 8 broad trapezoidal teeth, outer/root/hole radii in icon units ----------
def cog_path(cx, cy, R, r, h, n=8, rot_deg=15, tip=0.50, root=0.74):
    step = 2*math.pi/n; rot = math.radians(rot_deg)
    pts = []
    for i in range(n):
        a = i*step + rot
        pts += [(a - step*0.5*root, r), (a - step*0.5*tip, R), (a + step*0.5*tip, R), (a + step*0.5*root, r)]
    P = lambda a, rad: f"{cx+rad*math.sin(a):.1f},{cy-rad*math.cos(a):.1f}"
    d = f"M {P(*pts[0])} "
    for k in range(1, len(pts)):
        a, rad = pts[k]; pr = pts[k-1][1]
        if rad == R and pr == R: d += f"A {R} {R} 0 0 1 {P(a, rad)} "
        elif rad == r and pr == r: d += f"A {r} {r} 0 0 1 {P(a, rad)} "
        else: d += f"L {P(a, rad)} "
    d += f"A {r} {r} 0 0 1 {P(*pts[0])} Z "
    d += f"M {cx},{cy-h} A {h} {h} 0 1 0 {cx},{cy+h} A {h} {h} 0 1 0 {cx},{cy-h} Z"
    return d

# ---------- Tapered crack: a polyline turned into a polygon whose width shrinks to a point ----------
def crack(points, w0):
    n = len(points); left = []; right = []
    for i, (x, y) in enumerate(points):
        ax, ay = points[max(i-1, 0)]; bx, by = points[min(i+1, n-1)]
        dx, dy = bx-ax, by-ay; L = math.hypot(dx, dy) or 1
        nx, ny = -dy/L, dx/L
        w = w0*(1 - i/(n-1))**0.8 + 0.6
        left.append((x+nx*w, y+ny*w)); right.append((x-nx*w, y-ny*w))
    poly = left + right[::-1]
    return "M " + " L ".join(f"{x:.1f},{y:.1f}" for x, y in poly) + " Z"

